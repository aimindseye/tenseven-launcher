#!/usr/bin/env python3
"""Tabler Icons for Tenseven: import, generate, check.

Tenseven draws its glyphs from the Tabler Icons outline set (MIT), pinned in
third_party/tabler-icons. This script has three jobs:

  import --from DIR    Copy the SVGs Tenseven uses, byte for byte, from an extracted
                       @tabler/icons npm package (DIR contains icons/outline/*.svg) into
                       third_party/tabler-icons/icons/outline and rewrite ICON_MANIFEST.tsv.
  generate             Write the Kotlin glyph table (TablerGlyphPaths.kt) and the launcher
                       icon vectors from the verbatim SVGs.
  check                Write nothing; exit 1 if the manifest, the SVGs or the generated
                       files are out of date. CI runs this (tests/run.sh).

Which icons are used is read from the code: every AppGlyph("tabler-name", ...) entry in
AppGlyphs.kt, plus EXTRA_ICONS below (the launcher icon). Adding a glyph is: add the name
to AppGlyphs.kt, run `import --from <package dir>`, then `generate`.
"""
import argparse
import hashlib
import os
import re
import shutil
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLER = os.path.join(ROOT, "third_party", "tabler-icons")
SVG_DIR = os.path.join(TABLER, "icons", "outline")
MANIFEST = os.path.join(TABLER, "ICON_MANIFEST.tsv")
APP_GLYPHS = os.path.join(ROOT, "app", "src", "main", "java", "io", "github", "aimindseye", "tenseven", "model", "AppGlyphs.kt")
KOTLIN_OUT = os.path.join(ROOT, "app", "src", "main", "java", "io", "github", "aimindseye", "tenseven", "model", "TablerGlyphPaths.kt")
RES = os.path.join(ROOT, "app", "src", "main", "res")

# Icons used outside AppGlyph: name -> why.
EXTRA_ICONS = {"keyboard": "launcher icon (adaptive icon foreground)"}

# Launcher icon (Tenseven's own look, not SableOS's): deep navy, white Tabler glyph, amber dot.
ICON_NAME = "ic_tenseven"
ICON_GLYPH = "keyboard"
ICON_BG = "#0E1726"
ICON_FG = "#F4F6FA"
ICON_ACCENT = "#F2A93B"
CANVAS = 108.0
GLYPH_BOX = 40.0  # dp the 24-unit Tabler box is scaled to; the 66 dp safe zone holds it
GLYPH_SCALE = GLYPH_BOX / 24.0
GLYPH_OFFSET = (CANVAS - GLYPH_BOX) / 2.0

SVG_NS = "{http://www.w3.org/2000/svg}"
NAME_RE = re.compile(r'^\s+[A-Z_0-9]+\("([a-z0-9-]+)",\s*0x', re.M)


def sha256(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def used_icons():
    with open(APP_GLYPHS, encoding="utf-8") as f:
        names = set(NAME_RE.findall(f.read()))
    if not names:
        sys.exit("no AppGlyph entries found in " + APP_GLYPHS)
    return sorted(names | set(EXTRA_ICONS))


def manifest_rows(names):
    rows = ["icon\tsvg_sha256\tused_for"]
    glyph_names = set(NAME_RE.findall(open(APP_GLYPHS, encoding="utf-8").read()))
    for n in names:
        svg = os.path.join(SVG_DIR, n + ".svg")
        digest = sha256(svg) if os.path.exists(svg) else "MISSING"
        why = EXTRA_ICONS.get(n, "AppGlyph")
        if n in glyph_names and n in EXTRA_ICONS:
            why = "AppGlyph; " + why
        rows.append("%s\t%s\t%s" % (n, digest, why))
    return "\n".join(rows) + "\n"


def shape_to_path(el):
    """Tabler 3.x draws everything as <path>; the other shapes are converted for safety."""
    tag = el.tag.replace(SVG_NS, "")
    a = el.attrib
    if tag == "path":
        return a["d"]
    if tag == "circle":
        cx, cy, r = float(a["cx"]), float(a["cy"]), float(a["r"])
        return "M%g %ga%g %g 0 1 0 %g 0a%g %g 0 1 0 %g 0" % (cx - r, cy, r, r, 2 * r, r, r, -2 * r)
    if tag == "line":
        return "M%s %sL%s %s" % (a["x1"], a["y1"], a["x2"], a["y2"])
    if tag == "polyline":
        pts = a["points"].replace(",", " ").split()
        return "M" + " ".join(pts[:2]) + "L" + " ".join(pts[2:])
    if tag == "rect":
        x, y, w, h = (float(a.get(k, 0)) for k in ("x", "y", "width", "height"))
        return "M%g %gh%gv%gh%gz" % (x, y, w, h, -w)
    raise SystemExit("unsupported SVG element <%s> in a Tabler icon" % tag)


def icon_paths(name):
    """The drawable path data of one icon, one string per element (the 24x24 bounding box is skipped)."""
    svg = os.path.join(SVG_DIR, name + ".svg")
    if not os.path.exists(svg):
        raise SystemExit("missing SVG: %s (run: tools/tabler_icons.py import --from <package dir>)" % svg)
    root = ET.parse(svg).getroot()
    out = []
    for el in root:
        if el.attrib.get("stroke") == "none":
            continue
        out.append(shape_to_path(el))
    if not out:
        raise SystemExit("no drawable elements in " + svg)
    return out


def kotlin_table():
    glyph_names = sorted(set(NAME_RE.findall(open(APP_GLYPHS, encoding="utf-8").read())) | set(EXTRA_ICONS))
    lines = [
        "// GENERATED by tools/tabler_icons.py from third_party/tabler-icons. Do not edit; run the tool.",
        "// Tabler Icons: MIT, Copyright (c) 2020-2026 Pawel Kuna. See third_party/tabler-icons/LICENSE.",
        "package io.github.aimindseye.tenseven.model",
        "",
        "/**",
        " * Tabler outline icon geometry: 24 x 24 box, drawn with a 2 unit round-capped stroke. One string per",
        " * SVG element (never joined, because a relative moveto starts from the previous element's last point).",
        " */",
        "internal object TablerGlyphPaths {",
        "    const val VIEWPORT = 24f",
        "    const val STROKE = 2f",
        "",
        "    val BY_NAME: Map<String, List<String>> =",
        "        mapOf(",
    ]
    for n in glyph_names:
        elems = ",\n".join('                "%s"' % d.replace("\\", "\\\\").replace('"', '\\"') for d in icon_paths(n))
        lines.append('            "%s" to\n            listOf(\n%s,\n            ),' % (n, elems))
    lines += ["        )", "}", ""]
    return "\n".join(lines)


def vector(width_dp, body):
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- GENERATED by tools/tabler_icons.py. Do not edit. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="%gdp"\n    android:height="%gdp"\n'
        '    android:viewportWidth="%g"\n    android:viewportHeight="%g">\n%s</vector>\n'
    ) % (width_dp, width_dp, CANVAS, CANVAS, body)


def glyph_group(color):
    paths = "".join(
        '        <path\n            android:pathData="%s"\n            android:strokeColor="%s"\n'
        '            android:strokeWidth="2"\n            android:strokeLineCap="round"\n'
        '            android:strokeLineJoin="round" />\n' % (d, color)
        for d in icon_paths(ICON_GLYPH)
    )
    return (
        '    <group\n        android:scaleX="%g"\n        android:scaleY="%g"\n'
        '        android:translateX="%g"\n        android:translateY="%g">\n%s    </group>\n'
        % (GLYPH_SCALE, GLYPH_SCALE, GLYPH_OFFSET, GLYPH_OFFSET, paths)
    )


def launcher_files():
    accent = (
        '    <path\n        android:fillColor="%s"\n'
        '        android:pathData="M54,76m-2.5,0a2.5,2.5 0 1,1 5,0a2.5,2.5 0 1,1 -5,0" />\n' % ICON_ACCENT
    )
    adaptive = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- GENERATED by tools/tabler_icons.py. Do not edit. -->\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@drawable/%(n)s_background" />\n'
        '    <foreground android:drawable="@drawable/%(n)s_foreground" />\n'
        '    <monochrome android:drawable="@drawable/%(n)s_monochrome" />\n'
        '</adaptive-icon>\n' % {"n": ICON_NAME}
    )
    background = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- GENERATED by tools/tabler_icons.py. Do not edit. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
        '    <path\n        android:fillColor="%s"\n        android:pathData="M0,0h108v108h-108z" />\n</vector>\n' % ICON_BG
    )
    return {
        "drawable/%s_background.xml" % ICON_NAME: background,
        "drawable/%s_foreground.xml" % ICON_NAME: vector(108, glyph_group(ICON_FG) + accent),
        "drawable/%s_monochrome.xml" % ICON_NAME: vector(108, glyph_group("#FF000000")),
        "mipmap-anydpi-v26/%s.xml" % ICON_NAME: adaptive,
        "mipmap-anydpi-v26/%s_round.xml" % ICON_NAME: adaptive,
    }


def generated():
    names = used_icons()
    files = {os.path.relpath(KOTLIN_OUT, ROOT): kotlin_table()}
    for rel, text in launcher_files().items():
        files[os.path.relpath(os.path.join(RES, rel), ROOT)] = text
    files[os.path.relpath(MANIFEST, ROOT)] = manifest_rows(names)
    return files


def cmd_import(args):
    src = os.path.join(args.source, "icons", "outline")
    if not os.path.isdir(src):
        sys.exit("not an extracted @tabler/icons package: " + src)
    os.makedirs(SVG_DIR, exist_ok=True)
    for old in os.listdir(SVG_DIR):
        if old.endswith(".svg"):
            os.remove(os.path.join(SVG_DIR, old))
    for n in used_icons():
        f = os.path.join(src, n + ".svg")
        if not os.path.exists(f):
            sys.exit("Tabler has no outline icon named '%s' (see AppGlyphs.kt)" % n)
        shutil.copyfile(f, os.path.join(SVG_DIR, n + ".svg"))
    print("imported %d icons" % len(used_icons()))
    cmd_generate(args)


def cmd_generate(_args):
    for rel, text in generated().items():
        path = os.path.join(ROOT, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote", rel)


def cmd_check(_args):
    bad = 0
    names = used_icons()
    present = {f[:-4] for f in os.listdir(SVG_DIR)} if os.path.isdir(SVG_DIR) else set()
    for n in sorted(set(names) - present):
        print("FAIL missing SVG:", n)
        bad += 1
    for n in sorted(present - set(names)):
        print("FAIL unused SVG (remove it or use it):", n)
        bad += 1
    if bad:
        return 1
    for rel, text in generated().items():
        path = os.path.join(ROOT, rel)
        if not os.path.exists(path):
            print("FAIL missing generated file:", rel)
            bad += 1
        elif open(path, encoding="utf-8").read() != text:
            print("FAIL out of date (run tools/tabler_icons.py generate):", rel)
            bad += 1
    if not bad:
        print("PASS tabler icons: %d icons, manifest and generated files current" % len(names))
    return 1 if bad else 0


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    i = sub.add_parser("import")
    i.add_argument("--from", dest="source", required=True)
    sub.add_parser("generate")
    sub.add_parser("check")
    args = p.parse_args()
    rc = {"import": cmd_import, "generate": cmd_generate, "check": cmd_check}[args.cmd](args)
    sys.exit(rc or 0)


if __name__ == "__main__":
    main()
